#elif DT_NODE_HAS_STATUS_OKAY(DT_NODELABEL(i2c01))
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (1)
#elif DT_NODE_HAS_STATUS_OKAY(DT_NODELABEL(i2c10))
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (10)
#elif DT_NODE_HAS_STATUS_OKAY(DT_NODELABEL(i2c11))
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (11)
#elif DT_NODE_HAS_STATUS_OKAY(DT_NODELABEL(i2c20))
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (20)
#elif DT_NODE_HAS_STATUS_OKAY(DT_NODELABEL(i2c21))
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (21)
#else
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (-1)
#endif /* DT_NODE_HAS_STATUS_OKAY */
#else
#define SAU_I2C_CFG_SINGLE_CHANNEL_ENABLE (-1)
#endif /* DT_NUM_INST_STATUS_OKAY */

